import { createHash, createPublicKey } from "node:crypto";
import { chmod, mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { AppError } from "@nexus/shared";
import {
  ConnectorConfigError,
  parseConnectorConfig,
  usableKeysFor,
  type ConnectorConfig,
} from "./config.js";

/**
 * The administrative surface a future installer will drive.
 *
 * ## Why this exists as a library and not a CLI
 *
 * Because the installer, a future dashboard and the test suite all need the
 * same four operations, and the one thing that must not happen is three
 * implementations of "register a key" that disagree about what a valid key is.
 * The shell wrapper around this is somebody else's commit.
 *
 * ## What it refuses to do
 *
 * - **Never writes key material it was not given.** There is no key
 *   generation here. A client generates its own pair and hands over the public
 *   half; a connector that minted keys for clients would, at some point, have
 *   held their private halves.
 * - **Never overwrites a configuration it did not read.** Every mutation
 *   re-reads, edits and writes atomically, so a concurrent edit is lost
 *   loudly rather than silently.
 * - **Never reports a key.** `status` returns fingerprints. An operator
 *   confirming "the key I registered is the one in use" needs to compare, not
 *   to read, and a full key in a terminal ends up in a screenshot.
 */

export class ConnectorAdminError extends AppError {
  readonly code = "CONNECTOR_ADMIN_REFUSED";
  readonly httpStatus = 400;

  constructor(message: string, userMessage: string) {
    super({ message, userMessage });
  }
}

/** A fingerprint an operator can compare without handling key material. */
export function keyFingerprint(publicKeyPem: string): string {
  let der: Buffer;
  try {
    der = createPublicKey(publicKeyPem).export({ type: "spki", format: "der" });
  } catch {
    throw new ConnectorAdminError(
      "public key is not a parseable SPKI key",
      "That public key could not be read.",
    );
  }
  // Truncated to 16 hex characters: long enough that two keys will not collide
  // in any realistic installation, short enough to read aloud.
  return createHash("sha256").update(der).digest("hex").slice(0, 16);
}

export interface ConnectorKeyStatus {
  fingerprint: string;
  label: string | null;
  addedAt: string | null;
  revokedAt: string | null;
  usable: boolean;
}

export interface ConnectorClientStatus {
  clientId: string;
  enabled: boolean;
  keys: ConnectorKeyStatus[];
  /** True when at least one key can currently verify a request. */
  canAuthenticate: boolean;
}

export interface ConnectorStatus {
  configPath: string;
  /** False when no configuration file exists yet. */
  initialised: boolean;
  listen: ConnectorConfig["listen"] | null;
  acceptanceWindowMs: number | null;
  clockSkewMs: number | null;
  clients: ConnectorClientStatus[];
  /** True when nothing can authenticate — the correct state before setup. */
  closed: boolean;
}

export interface InitOptions {
  configPath: string;
  listen?: ConnectorConfig["listen"];
}

/**
 * Creates a configuration that accepts nobody.
 *
 * Closed by default, deliberately: an installer that has not yet registered a
 * client should leave a connector that refuses everything, not one waiting to
 * be claimed. Refuses to overwrite, because the alternative is an installer
 * re-run wiping the keys somebody registered last month.
 */
export async function initConnector(options: InitOptions): Promise<ConnectorStatus> {
  const existing = await readRaw(options.configPath);
  if (existing !== undefined) {
    throw new ConnectorAdminError(
      `configuration already exists at ${options.configPath}`,
      "This connector is already set up.",
    );
  }
  const config = parseConnectorConfig({
    clients: [],
    ...(options.listen === undefined ? {} : { listen: options.listen }),
  });
  await writeConfig(options.configPath, config);
  return statusOf(options.configPath, config);
}

export interface RegisterKeyOptions {
  configPath: string;
  clientId: string;
  /** SPKI PEM public key, generated by the client. */
  publicKey: string;
  label?: string;
  now?: () => Date;
}

/**
 * Registers a public key for a client, creating the client if needed.
 *
 * Also the rotation primitive: registering a second key leaves both valid,
 * which is the overlap rotation needs, and the old one is withdrawn afterwards
 * with `revokeClientKey`.
 */
export async function registerClientKey(options: RegisterKeyOptions): Promise<ConnectorStatus> {
  const now = options.now ?? (() => new Date());
  return mutate(options.configPath, (config) => {
    // Parsed through the same schema the connector uses, so a key this accepts
    // is a key the connector will accept — and a private key pasted here is
    // refused by that schema rather than by a check somebody might forget.
    const fingerprint = keyFingerprint(options.publicKey);
    const clients = [...config.clients];
    const index = clients.findIndex((client) => client.clientId === options.clientId);
    const entry = {
      publicKey: options.publicKey,
      addedAt: now().toISOString(),
      ...(options.label === undefined ? {} : { label: options.label }),
    };

    if (index === -1) {
      clients.push({ clientId: options.clientId, keys: [entry], enabled: true });
      return { ...config, clients };
    }

    const current = clients[index];
    if (current === undefined)
      throw new ConnectorAdminError("client vanished", "Unexpected state.");
    const keys = current.publicKey === undefined ? [...(current.keys ?? [])] : migrate(current);
    if (keys.some((key) => keyFingerprint(key.publicKey) === fingerprint)) {
      // Idempotence matters for an installer that may be re-run: registering
      // the same key twice must not create a second entry that then has to be
      // revoked twice.
      throw new ConnectorAdminError(
        `key ${fingerprint} is already registered for ${options.clientId}`,
        "That key is already registered.",
      );
    }
    keys.push(entry);
    const { publicKey: _dropped, ...rest } = current;
    clients[index] = { ...rest, keys };
    return { ...config, clients };
  });
}

export interface RevokeKeyOptions {
  configPath: string;
  clientId: string;
  /** The fingerprint from `status`, so no key material has to be handled. */
  fingerprint: string;
  now?: () => Date;
}

/**
 * Withdraws one key.
 *
 * The entry is kept and marked, not deleted: an operator looking at this file
 * after an incident needs to see that a key was withdrawn and when, which a
 * deletion hides.
 */
export async function revokeClientKey(options: RevokeKeyOptions): Promise<ConnectorStatus> {
  const now = options.now ?? (() => new Date());
  return mutate(options.configPath, (config) => {
    const clients = [...config.clients];
    const index = clients.findIndex((client) => client.clientId === options.clientId);
    const current = index === -1 ? undefined : clients[index];
    if (current === undefined) {
      throw new ConnectorAdminError(
        `no client ${options.clientId}`,
        "That client is not registered.",
      );
    }

    const keys = current.publicKey === undefined ? [...(current.keys ?? [])] : migrate(current);
    const target = keys.findIndex((key) => keyFingerprint(key.publicKey) === options.fingerprint);
    if (target === -1) {
      throw new ConnectorAdminError(
        `client ${options.clientId} has no key ${options.fingerprint}`,
        "That key is not registered for this client.",
      );
    }
    const existing = keys[target];
    if (existing === undefined) throw new ConnectorAdminError("key vanished", "Unexpected state.");
    if (existing.revokedAt !== undefined) return config;
    keys[target] = { ...existing, revokedAt: now().toISOString() };
    const { publicKey: _dropped, ...rest } = current;
    clients[index] = { ...rest, keys };
    return { ...config, clients };
  });
}

export interface SetClientEnabledOptions {
  configPath: string;
  clientId: string;
  enabled: boolean;
}

/**
 * Turns a client off without touching its keys.
 *
 * Distinct from revocation on purpose: disabling is reversible and says
 * nothing about whether the key material is compromised. Conflating the two
 * means an operator who wanted to pause a client has to re-register it.
 */
export async function setClientEnabled(options: SetClientEnabledOptions): Promise<ConnectorStatus> {
  return mutate(options.configPath, (config) => {
    const clients = [...config.clients];
    const index = clients.findIndex((client) => client.clientId === options.clientId);
    const current = index === -1 ? undefined : clients[index];
    if (current === undefined) {
      throw new ConnectorAdminError(
        `no client ${options.clientId}`,
        "That client is not registered.",
      );
    }
    clients[index] = { ...current, enabled: options.enabled };
    return { ...config, clients };
  });
}

/** Reports what the connector would accept, without revealing any key. */
export async function connectorStatus(configPath: string): Promise<ConnectorStatus> {
  const raw = await readRaw(configPath);
  if (raw === undefined) {
    return {
      configPath,
      initialised: false,
      listen: null,
      acceptanceWindowMs: null,
      clockSkewMs: null,
      clients: [],
      closed: true,
    };
  }
  return statusOf(configPath, parseConnectorConfig(JSON.parse(raw)));
}

/** The conventional configuration location inside a state directory. */
export function defaultConfigPath(stateDir: string): string {
  return join(stateDir, "connector.json");
}

function statusOf(configPath: string, config: ConnectorConfig): ConnectorStatus {
  const clients = config.clients.map((client) => {
    const keys = client.publicKey === undefined ? (client.keys ?? []) : migrate(client);
    return {
      clientId: client.clientId,
      enabled: client.enabled,
      keys: keys.map((key) => ({
        fingerprint: keyFingerprint(key.publicKey),
        label: key.label ?? null,
        addedAt: key.addedAt ?? null,
        revokedAt: key.revokedAt ?? null,
        usable: client.enabled && key.revokedAt === undefined,
      })),
      canAuthenticate: usableKeysFor(client).length > 0,
    };
  });
  return {
    configPath,
    initialised: true,
    listen: config.listen,
    acceptanceWindowMs: config.acceptanceWindowMs,
    clockSkewMs: config.clockSkewMs,
    clients,
    closed: clients.every((client) => !client.canAuthenticate),
  };
}

/** Lifts a legacy single-key client into the rotation shape, without losing it. */
function migrate(
  client: ConnectorConfig["clients"][number],
): { publicKey: string; addedAt?: string; revokedAt?: string; label?: string }[] {
  return client.publicKey === undefined ? [] : [{ publicKey: client.publicKey }];
}

async function mutate(
  configPath: string,
  edit: (config: ConnectorConfig) => ConnectorConfig,
): Promise<ConnectorStatus> {
  const raw = await readRaw(configPath);
  if (raw === undefined) {
    throw new ConnectorAdminError(
      `no configuration at ${configPath}`,
      "This connector is not set up yet.",
    );
  }
  const edited = edit(parseConnectorConfig(JSON.parse(raw)));
  // Re-parsed after editing: the result has to satisfy the same schema the
  // connector loads, or an admin operation could write a file that refuses to
  // start.
  const validated = parseConnectorConfig(edited);
  await writeConfig(configPath, validated);
  return statusOf(configPath, validated);
}

async function readRaw(configPath: string): Promise<string | undefined> {
  try {
    return await readFile(configPath, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw new ConnectorConfigError(`cannot read ${configPath}`);
  }
}

async function writeConfig(configPath: string, config: ConnectorConfig): Promise<void> {
  await mkdir(dirname(configPath), { recursive: true, mode: 0o700 });
  const temporary = `${configPath}.${String(process.pid)}.tmp`;
  // Write then rename: a crash leaves the previous configuration intact rather
  // than a truncated file that locks everybody out.
  await writeFile(temporary, `${JSON.stringify(config, null, 2)}\n`, {
    encoding: "utf8",
    mode: 0o600,
  });
  await chmod(temporary, 0o600);
  await rename(temporary, configPath);
}
