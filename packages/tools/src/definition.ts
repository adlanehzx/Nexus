import type { z } from "zod";
import type { RiskLevel } from "./risk.js";
import type { Permission } from "./permissions.js";
import type { NormalizedToolError } from "./errors.js";

/**
 * Context passed to a tool during its execution.
 * Contains zero third-party secrets; credentials are resolved post-authorization.
 */
export interface ToolContext {
  runId: string;
  userId: string;
  conversationId: string;
  correlationId: string;
  signal: AbortSignal;
  idempotencyKey: string;
  attempt: number;
  onProgress: (progress: ToolProgress) => void;
}

export interface ToolProgress {
  pct?: number;
  label?: string;
  chunk?: string;
}

/**
 * Tool definition contract.
 * `execute` returns the output or throws an Error.
 */
export interface ToolDefinition<TInput = unknown, TOutput = unknown> {
  name: string;
  description: string;
  version?: string;

  inputSchema: z.ZodType<TInput>;
  outputSchema: z.ZodType<TOutput>;

  /** Optional raw JSON Schema for dynamically discovered tools (e.g. MCP servers). */
  inputJsonSchema?: Record<string, unknown>;

  riskLevel: RiskLevel;
  requiredPermissions: readonly Permission[];

  requiresConfirmation: boolean | ((input: TInput, context: ToolContext) => boolean);

  timeoutMs?: number;
  idempotent?: boolean;
  retry?: { attempts: number };
  summarize?: (input: TInput) => string;

  execute: (input: TInput, context: ToolContext) => Promise<TOutput>;
}

export type AnyToolDefinition = ToolDefinition<never, unknown>;

export interface ToolMetrics {
  durationMs: number;
  attempts: number;
}

/** Execution result generated by the executor. */
export type ToolResult<TOutput = unknown> =
  | {
      ok: true;
      toolName: string;
      output: TOutput;
      summaryForModel: string;
      metrics: ToolMetrics;
    }
  | {
      ok: false;
      toolName: string;
      error: NormalizedToolError;
      summaryForModel: string;
      metrics: ToolMetrics;
    };

/** Evaluates whether a tool execution requires human confirmation. */
export function toolRequiresConfirmation<I, O>(
  tool: ToolDefinition<I, O>,
  input: I,
  context: ToolContext,
): boolean {
  return typeof tool.requiresConfirmation === "function"
    ? tool.requiresConfirmation(input, context)
    : tool.requiresConfirmation;
}
